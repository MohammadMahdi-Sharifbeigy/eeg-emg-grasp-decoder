def _cell(kind, src):
    lines = src.rstrip("\n").split("\n")
    source = [line + "\n" for line in lines[:-1]] + [lines[-1]]
    if kind == "markdown":
        return {"cell_type": "markdown", "metadata": {}, "source": source}
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": source}


def build() -> dict:
    cells = [("markdown", TITLE), ("code", SETUP),
             ("markdown", A_MD), ("code", A_RUN), ("code", A_PLOT),
             ("markdown", B_MD), ("code", B_RUN), ("code", B_PLOT),
             ("markdown", C_MD), ("code", C_RUN), ("code", C_PLOT)]
    return {"cells": [_cell(k, s) for k, s in cells],
            "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                         "language_info": {"name": "python"}},
            "nbformat": 4, "nbformat_minor": 5}


if __name__ == "__main__":
    Path("eeg_controls.ipynb").write_text(json.dumps(build(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote eeg_controls.ipynb")
