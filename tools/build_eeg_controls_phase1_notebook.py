W_MD = """## W. Weight check: does E give heavy lifts a higher level than light ones?

For every test lift with a known weight (CurW 1, 2, 4 = light, medium, heavy), the **level** is the mean envelope of the
target and of each output (K, E, F) per muscle in two windows: *hold* (lift-off + 0.5 s to replace - 0.2 s, the main window)
and *load* (first touch to lift-off). The checkpoints are the non-causal v2 models in `outputs/checkpoints_v2`.
**E_cal** is E multiplied by one gain per muscle, fitted on the validation lifts: it shows how much of the level error a
single rescaling fixes, and whether a weight difference shows once the size is right.

**What the numbers mean.** `rho_weight` is the Spearman correlation of the lift level with the weight (the target's is the
reference). `ratio_heavy_light` is the mean level of heavy over light lifts. `slope` is the slope of output level on target
level over lifts (1 = right size, below 1 = shrunk toward the mean). `size_ratio` is mean output over mean target.

**How to read the figures.**

- **W1** (mean level per weight, per muscle): the target rises from light to heavy. A *good for EEG* E rises too, even if it is
  too low; E_cal then sits on the target. If E is *flat* across weights while E_cal is on the target only on average, the EEG
  carries timing but no force information.
- **W2** (lift by lift, E against target level, colours = weight): good is a cloud along the identity line, with dark (heavy)
  points above light ones. Only timing looks like a horizontal band: all lifts get the same level whatever the target.
- **W3** (a stretch of one test series with lifts of different weights): look at whether E's bursts differ in height between
  light and heavy lifts, and whether E_cal follows the target's height.
- **W4** (per participant): rho and slope for E and K. Good is rho of E clearly above 0 in most participants and a slope
  above 0; K is the reference for what the kinematics give.

The printout after the figures gives E's `rho_weight` and heavy/light ratio against the target's, and the group tests over
participants (Wilcoxon).
"""

